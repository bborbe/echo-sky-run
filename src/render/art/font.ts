/** The width in pixels of a line of text. */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP
}

/** Characters the font cannot draw — the test keeps every overlay line free of them. */
export function missingGlyphs(text: string): string[] {
  return [...new Set(text.split(''))].filter((ch) => FONT[ch] === undefined)
}

